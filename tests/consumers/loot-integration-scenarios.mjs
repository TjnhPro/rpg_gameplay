import test from 'node:test';
import assert from 'node:assert/strict';

// Test-local L4 handoff only. The two runners supply the built or installed root.
export function lootIntegrationTests(g) {
 const table=()=>({tableId:'fixture',noDropWeight:60,entries:[
  {entryId:'p',definitionId:'potion',weight:30,quantity:2},
  {entryId:'s',definitionId:'sword',weight:10,quantity:1},
 ]});
 const potion={tableId:'fixture',drops:[{entryId:'p',definitionId:'potion',quantity:2}]};
 const sword={tableId:'fixture',drops:[{entryId:'s',definitionId:'sword',quantity:1}]};
 const owner={ownerKind:'player',ownerId:'recipient'};
 function setup(maxStackQuantity=10) {
  const definitions=['potion','sword'].map(definitionId=>g.createItemDefinition({definitionId},
   {categoryId:null,tagIds:[],rarityId:null,properties:{catalog:{source:'L3'}}}));
  const context={items:definitions.map(definition=>({definition,
   stackPolicy:{stackable:definition.definitionId==='potion'},
   maxStackQuantity:definition.definitionId==='potion'?maxStackQuantity:null}))};
  const state=g.createInventoryState({inventoryId:'bag',owner,entries:[]},context);
  return {definitions,context,state};
 }
 function frozen(value) {
  if(value!==null&&typeof value==='object') {
   assert.ok(Object.isFrozen(value),'deep immutable snapshot');
   for(const child of Object.values(value))frozen(child);
  }
 }
 // Supplied IDs are explicit facts, not generated by Loot. No commit on any rejection.
 function deliver(result,state,context,{instanceId='caller-A',nextId=()=>instanceId,maxEntries=2,eligible=true}={}) {
  const calls={item:0,inventory:0,id:0};
  if(result.drops.length===0)return {state,calls,delivery:'no-drop'};
  const [drop]=result.drops;
  const fact=context.items.find(x=>x.definition.definitionId===drop.definitionId);
  if(!fact)return {state,calls,delivery:'unresolved'};
  calls.id++;
  const suppliedId=nextId();
  calls.item++;
  const item=g.createItemInstance(fact.definition,{instanceId:suppliedId,properties:{origin:{event:'fixture'}}});
  calls.inventory++;
  const transition=g.addInventoryEntry(state,context,{item,quantity:drop.quantity},{maxEntries},{eligible});
  return {state:transition.status==='accepted'?transition.candidate:state,calls,delivery:transition.status,transition};
 }

 test('LT11/LT12 literal no-drop, potion and sword handoffs preserve caller commit authority',()=>{
  const {state,context}=setup();
  const validated=g.validateLootTableDefinition(table());
  const none=g.validateLootRollResult(g.rollLootTable(validated,0.10));
  assert.deepEqual(none,{tableId:'fixture',drops:[]});
  const empty=deliver(none,state,context,{nextId(){throw new Error('no-drop ID provider called');}});
  assert.deepEqual(empty,{state,calls:{item:0,inventory:0,id:0},delivery:'no-drop'});
  assert.equal(empty.state,state,'no-drop keeps current state identity');
  const chosen=g.validateLootRollResult(g.rollLootTable(validated,0.60));
  assert.deepEqual(chosen,potion);
  const sent=deliver(chosen,state,context);
  const potionItem={instanceId:'caller-A',definitionId:'potion',properties:{origin:{event:'fixture'}}};
  assert.deepEqual(sent.transition,{status:'accepted',reason:'none',candidate:{inventoryId:'bag',owner,
   entries:[{item:potionItem,quantity:2}]}});
  assert.deepEqual(sent.calls,{item:1,inventory:1,id:1});
  assert.deepEqual(state,{inventoryId:'bag',owner,entries:[]});
  assert.deepEqual(g.listInventoryEntries(sent.state,context),[{item:potionItem,quantity:2}]);
  const blade=g.rollLootTable(validated,0.90);assert.deepEqual(blade,sword);
  const both=deliver(blade,sent.state,context,{instanceId:'caller-B'});
  assert.deepEqual(both.state.entries,[{item:potionItem,quantity:2},
   {item:{instanceId:'caller-B',definitionId:'sword',properties:{origin:{event:'fixture'}}},quantity:1}]);
  assert.equal(new Set(both.state.entries.map(x=>x.item.instanceId)).size,2);
  frozen(chosen);frozen(sent.transition);frozen(both.state);
 });

 test('LT12 rejected delivery retains selected intent and current state without duplicate grant',()=>{
  const {state,context}=setup();const result=g.rollLootTable(table(),0.60);
  for(const [options,reason] of [[{maxEntries:0},'capacity_exceeded'],[{eligible:false},'ineligible']]) {
   const denied=deliver(result,state,context,options);
   assert.deepEqual(denied.transition,{status:'rejected',reason,candidate:null});
   assert.equal(denied.state,state,'rejected add cannot commit');
   assert.equal(denied.delivery,'rejected');assert.deepEqual(result,potion);
  }
  const low=setup(1),overflow=deliver(result,low.state,low.context);
  assert.deepEqual(overflow.transition,{status:'rejected',reason:'stack_limit_exceeded',candidate:null});
  assert.equal(overflow.state,low.state);assert.deepEqual(result,potion,'no silent stack splitting');
  const unresolved=deliver(result,state,{items:[]});
  assert.deepEqual(unresolved,{state,calls:{item:0,inventory:0,id:0},delivery:'unresolved'});
  const malformed={items:[{...context.items[0],definition:{definitionId:'potion'}}]};
  assert.throws(()=>deliver(result,state,malformed),TypeError);assert.deepEqual(state.entries,[]);
  const first=deliver(result,state,context),duplicate=deliver(result,first.state,context);
  assert.deepEqual(duplicate.transition,{status:'rejected',reason:'already_present',candidate:null});
  assert.equal(duplicate.state,first.state);assert.equal(duplicate.state.entries.length,1);
 });

 test('LT13 distinct Text, 2D and 2.5D data profiles use identical source-neutral APIs',()=>{
  const profiles=[
   {source:{kind:'quest',id:'dialogue-7'},table:{tableId:'text',noDropWeight:1,
    entries:[{entryId:'r',definitionId:'potion',weight:1,quantity:3}]},sample:0.5,
    expected:{tableId:'text',drops:[{entryId:'r',definitionId:'potion',quantity:3}]},capacity:1},
   {source:{kind:'chest',id:'tile-8'},table:{tableId:'2d',noDropWeight:0,
    entries:[{entryId:'w',definitionId:'sword',weight:2,quantity:1},
     {entryId:'p',definitionId:'potion',weight:1,quantity:4}]},sample:0,
    expected:{tableId:'2d',drops:[{entryId:'w',definitionId:'sword',quantity:1}]},capacity:2},
   {source:{kind:'encounter',id:'arena-9'},table:{tableId:'2.5d',noDropWeight:3,
    entries:[{entryId:'cache',definitionId:'potion',weight:1,quantity:5}]},sample:0.5,
    expected:{tableId:'2.5d',drops:[]},capacity:0},
  ];
  for(const profile of profiles) {
   const before=structuredClone(profile);const {state,context}=setup();
   const captured=g.createLootTableDefinition(profile.table);
   const result=g.rollLootTable(captured,profile.sample);assert.deepEqual(result,profile.expected);
   const sent=deliver(result,state,context,{instanceId:profile.source.id,maxEntries:profile.capacity});
   const expected=profile.table.tableId==='text'
    ?[{item:{instanceId:'dialogue-7',definitionId:'potion',properties:{origin:{event:'fixture'}}},quantity:3}]
    :profile.table.tableId==='2d'
     ?[{item:{instanceId:'tile-8',definitionId:'sword',properties:{origin:{event:'fixture'}}},quantity:1}]:[];
   assert.deepEqual(sent.state.entries,expected);assert.deepEqual(profile,before);
   assert.deepEqual(state.entries,[]);frozen(result);frozen(sent.state);
  }
 });

 test('LT14 explicit Foundation sample and caller IDs replay without implicit RNG or clock',()=>{
  const {state,context}=setup();const random=Math.random,now=Date.now;
  let samples=0,clock=0,ids=0;
  try {
   Math.random=()=>{throw new Error('implicit RNG');};Date.now=()=>{throw new Error('implicit clock');};
   const execution=g.createExecutionContext({clock:{now(){clock++;return 42;}},
    random:{next(){samples++;return 0.60;}},ids:{next(){ids++;return 'unused';}}});
   assert.equal(samples,0);
   const result=g.rollLootTable(table(),g.nextExecutionRandom(execution));
   assert.deepEqual(result,potion);assert.equal(samples,1);assert.equal(clock,0);assert.equal(ids,0);
   const again=g.rollLootTable(table(),0.60);assert.deepEqual(again,result);assert.notEqual(again,result);
   const a=deliver(result,state,context,{instanceId:'replay-A'}),b=deliver(again,state,context,{instanceId:'replay-B'});
   assert.equal(a.state.entries[0].item.instanceId,'replay-A');assert.equal(b.state.entries[0].item.instanceId,'replay-B');
   assert.deepEqual(a.state.entries[0].item.properties,b.state.entries[0].item.properties);
   assert.deepEqual(result,potion);assert.equal(samples,1);
  } finally {Math.random=random;Date.now=now;}
 });

 test('LT14 hostile inputs reject safely and Loot/Item/context snapshots remain isolated',()=>{
  const input=table(),before=structuredClone(input);let reads=0;
  assert.throws(()=>g.rollLootTable({...input,get entries(){reads++;return [];}},0.60),TypeError);
  assert.equal(reads,0);assert.deepEqual(input,before);assert.equal(Object.isFrozen(input),false);
  const result=g.rollLootTable(input,0.60);input.entries[0].quantity=99;assert.deepEqual(result,potion);
  const {state,context}=setup(),contextBefore=structuredClone(context);
  const properties={origin:{event:'caller'}};
  const item=g.createItemInstance(context.items[0].definition,{instanceId:'isolated',properties});
  const admitted=g.addInventoryEntry(state,context,{item,quantity:2},{maxEntries:1},{eligible:true});
  assert.equal(admitted.status,'accepted');
  properties.origin.event='changed';assert.equal(item.properties.origin.event,'caller');
  context.items[0].maxStackQuantity=1;
  assert.deepEqual(admitted.candidate.entries,[{item:{instanceId:'isolated',definitionId:'potion',
   properties:{origin:{event:'caller'}}},quantity:2}]);
  assert.deepEqual(state.entries,[]);assert.equal(Object.isFrozen(properties.origin),false);
  assert.equal(Object.isFrozen(context.items[0]),false);
  assert.deepEqual(context.items[0].definition,contextBefore.items[0].definition);
  frozen(result);frozen(item);frozen(admitted);
  assert.throws(()=>{result.drops[0].quantity=9;},TypeError);
  assert.throws(()=>{admitted.candidate.entries[0].item.properties.origin.event='bad';},TypeError);
 });
}
